//! Fixtures shared with the Android app (android/): real folder and song names with the answers
//! this desktop code gives for them. The Android port of Tidy Names and the folder order is
//! tested against the same file, so both apps show the same names in the same order.
//!
//! `shared_fixtures_match` (a normal test) checks this code still gives those answers.
//! To regenerate after a deliberate change to the rules:
//!   RYUON_FIXTURE_TAGS=tags.tsv RYUON_FIXTURE_NAMES=before.tsv \
//!     cargo test export_shared_fixtures -- --ignored
//! tags.tsv: path, title, artist, album (tab separated); before.tsv: path, anything.

use std::{collections::BTreeSet, fs, path::PathBuf};

use serde_json::{json, Value};

use crate::{library::cmp_components, tidy, utils::cmp_like_nautilus};

fn fixture_path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/ryuon-fixtures.json")
}

/// Folder paths in play order: compared folder by folder, the way the desktop queues a library
fn sort_folders(folders: &mut [String]) {
    folders.sort_by(|a, b| {
        let ca: Vec<String> = a.split('/').map(str::to_string).collect();
        let cb: Vec<String> = b.split('/').map(str::to_string).collect();
        cmp_components(&ca, &cb, cmp_like_nautilus)
    });
}

fn answers(inputs: &BTreeSet<String>, f: impl Fn(&str) -> Value) -> Value {
    Value::Array(inputs.iter().map(|i| json!([i, f(i)])).collect())
}

#[test]
#[ignore]
fn export_shared_fixtures() {
    let (mut names, mut titles, mut artists, mut folders) =
        (BTreeSet::new(), BTreeSet::new(), BTreeSet::new(), BTreeSet::new());
    for var in ["RYUON_FIXTURE_TAGS", "RYUON_FIXTURE_NAMES"] {
        let text = fs::read_to_string(std::env::var(var).unwrap_or_else(|_| panic!("{} not set", var))).unwrap();
        for line in text.lines() {
            let cols: Vec<&str> = line.split('\t').collect();
            // Every folder on the path, and the file name without its extension
            let parts: Vec<&str> = cols[0].split('/').collect();
            for i in 1..parts.len() {
                folders.insert(parts[..i].join("/"));
                names.insert(parts[i - 1].to_string());
            }
            let file = parts[parts.len() - 1];
            titles.insert(file.rsplit_once('.').map_or(file, |(stem, _)| stem).to_string());
            if var == "RYUON_FIXTURE_TAGS" {
                let col = |i: usize| cols.get(i).map(|s| s.trim_end().to_string()).filter(|s| !s.is_empty());
                if let Some(t) = col(1) {
                    titles.insert(t);
                }
                if let Some(a) = col(2) {
                    artists.insert(a);
                }
                if let Some(a) = col(3) {
                    names.insert(a);
                }
            }
        }
    }
    let mut order: Vec<String> = folders.into_iter().collect();
    sort_folders(&mut order);
    let out = json!({
        "about": "Real folder and song names with the desktop Ryuon's answers. Generated by src/shared_fixtures.rs; do not edit by hand.",
        "version": 1,
        "name": answers(&names, |s| json!(tidy::name(s))),
        "title": answers(&titles, |s| json!(tidy::title(s))),
        "artist": answers(&artists, |s| json!(tidy::artist(s))),
        "folder_order": order,
    });
    fs::create_dir_all(fixture_path().parent().unwrap()).unwrap();
    fs::write(fixture_path(), serde_json::to_string_pretty(&out).unwrap() + "\n").unwrap();
    println!(
        "wrote {}: {} names, {} titles, {} artists, {} folders",
        fixture_path().display(),
        out["name"].as_array().unwrap().len(),
        out["title"].as_array().unwrap().len(),
        out["artist"].as_array().unwrap().len(),
        out["folder_order"].as_array().unwrap().len()
    );
}

#[test]
fn shared_fixtures_match() {
    let text = fs::read_to_string(fixture_path()).expect("tests/fixtures/ryuon-fixtures.json");
    let fixtures: Value = serde_json::from_str(&text).unwrap();
    let check = |key: &str, f: &dyn Fn(&str) -> Value| {
        let mut wrong = Vec::new();
        for pair in fixtures[key].as_array().unwrap() {
            let (input, expected) = (pair[0].as_str().unwrap(), &pair[1]);
            let got = f(input);
            if &got != expected {
                wrong.push(format!("{} {:?}: expected {} got {}", key, input, expected, got));
            }
        }
        assert!(wrong.is_empty(), "{} {} differ:\n{}", wrong.len(), key, wrong.join("\n"));
    };
    check("name", &|s| json!(tidy::name(s)));
    check("title", &|s| json!(tidy::title(s)));
    check("artist", &|s| json!(tidy::artist(s)));

    let expected: Vec<String> = fixtures["folder_order"]
        .as_array()
        .unwrap()
        .iter()
        .map(|v| v.as_str().unwrap().to_string())
        .collect();
    let mut shuffled: Vec<String> = expected.iter().rev().cloned().collect();
    sort_folders(&mut shuffled);
    assert_eq!(shuffled, expected);
    assert_eq!(expected.len(), expected.iter().collect::<BTreeSet<_>>().len());
}
